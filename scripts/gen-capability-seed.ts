// Generates migrations/0004_capability_registry.sql from src/worker/catalog/capabilities.ts.
// Usage: node scripts/gen-capability-seed.ts
// Seeds are upsert-safe (ON CONFLICT DO NOTHING) so owner edits made in /admin survive re-runs.
import { writeFileSync } from 'node:fs';
import { ALIASES, CAPABILITIES } from '../src/worker/catalog/capabilities.ts';

const SEED_AT = '2026-10-30T00:00:00.000Z';
const q = (v: string | number | null) => (v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => q(JSON.stringify(v));

const schema = `-- Master spec v4.0 Phase 1: complete human-capability registry and Option B classification.
-- GENERATED by scripts/gen-capability-seed.ts from src/worker/catalog/capabilities.ts. Do not edit by hand.
-- Additive only: capability_requests gains nullable columns; no table is rebuilt.
PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS capabilities (
  id TEXT PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  number INTEGER,
  display_name TEXT NOT NULL,
  summary TEXT NOT NULL,
  example_intents_json TEXT NOT NULL DEFAULT '[]',
  deliverables_json TEXT NOT NULL DEFAULT '[]',
  required_skills_json TEXT NOT NULL DEFAULT '[]',
  location_type TEXT NOT NULL DEFAULT 'remote_or_on_site'
    CHECK (location_type IN ('remote','on_site','remote_or_on_site')),
  readiness TEXT NOT NULL DEFAULT 'inquiry_only'
    CHECK (readiness IN ('inquiry_only','human_reviewed_inquiry','pilot','live','future')),
  inquiry_enabled INTEGER NOT NULL DEFAULT 1 CHECK (inquiry_enabled IN (0,1)),
  authorization_requirements_json TEXT NOT NULL DEFAULT '[]',
  risk_tier TEXT NOT NULL DEFAULT 'medium' CHECK (risk_tier IN ('low','medium','high')),
  origin TEXT NOT NULL DEFAULT 'seed' CHECK (origin IN ('seed','admin')),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS capability_aliases (
  alias_slug TEXT NOT NULL,
  alias_name TEXT NOT NULL,
  capability_slug TEXT NOT NULL REFERENCES capabilities(slug) ON DELETE CASCADE,
  examples_json TEXT NOT NULL DEFAULT '[]',
  PRIMARY KEY (alias_slug, capability_slug)
);
CREATE INDEX IF NOT EXISTS idx_capability_aliases_capability ON capability_aliases(capability_slug);

-- Unfamiliar requests (spec 5.2): raw text stays on the request; this is the owner review queue.
CREATE TABLE IF NOT EXISTS candidate_capabilities (
  id TEXT PRIMARY KEY,
  request_id TEXT NOT NULL REFERENCES capability_requests(id) ON DELETE CASCADE,
  suggested_label TEXT,
  normalized_key TEXT,
  classifier_version TEXT NOT NULL DEFAULT 'hint-match-1',
  confidence REAL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','merged','rejected')),
  decided_capability_slug TEXT,
  decided_by TEXT,
  decided_at TEXT,
  created_at TEXT NOT NULL,
  UNIQUE (request_id, normalized_key)
);
CREATE INDEX IF NOT EXISTS idx_candidate_capabilities_status ON candidate_capabilities(status, created_at DESC);

-- Option B fields from spec 8.1 / 11.5. All optional; objective stays the canonical raw text.
ALTER TABLE capability_requests ADD COLUMN problem_statement TEXT;
ALTER TABLE capability_requests ADD COLUMN desired_outcome TEXT;
ALTER TABLE capability_requests ADD COLUMN service_tags_json TEXT NOT NULL DEFAULT '[]';
ALTER TABLE capability_requests ADD COLUMN evidence_requirements TEXT;
ALTER TABLE capability_requests ADD COLUMN preferred_rep_id TEXT;
ALTER TABLE capability_requests ADD COLUMN persona_id TEXT;
ALTER TABLE capability_requests ADD COLUMN authorization_description TEXT;
-- Classification is derived after the raw text is saved; untrusted until an admin confirms it.
ALTER TABLE capability_requests ADD COLUMN classification_state TEXT NOT NULL DEFAULT 'unclassified';
ALTER TABLE capability_requests ADD COLUMN classified_capabilities_json TEXT NOT NULL DEFAULT '[]';
CREATE INDEX IF NOT EXISTS idx_capability_requests_classification ON capability_requests(classification_state, created_at DESC);
`;

const seed = CAPABILITIES.map(
  (c) =>
    `INSERT INTO capabilities (id, slug, number, display_name, summary, example_intents_json, deliverables_json, required_skills_json, location_type, readiness, inquiry_enabled, authorization_requirements_json, risk_tier, origin, created_at, updated_at)
  VALUES (${q(`capdef_${String(c.number).padStart(2, '0')}`)}, ${q(c.slug)}, ${c.number}, ${q(c.name)}, ${q(c.summary)}, ${j(c.example_intents)}, ${j(c.deliverables)}, ${j(c.required_skills)}, ${q(c.location_type)}, ${q(c.readiness)}, 1, ${j(c.authorization_requirements)}, ${q(c.risk_tier)}, 'seed', ${q(SEED_AT)}, ${q(SEED_AT)})
  ON CONFLICT(slug) DO NOTHING;`,
).join('\n');

const aliasSeed = ALIASES.flatMap((a) =>
  a.maps_to.map(
    (target) =>
      `INSERT INTO capability_aliases (alias_slug, alias_name, capability_slug, examples_json) VALUES (${q(a.slug)}, ${q(a.name)}, ${q(target)}, ${j(a.examples)})
  ON CONFLICT(alias_slug, capability_slug) DO NOTHING;`,
  ),
).join('\n');

// Existing V1 requests: record any category hint that matches the registry (V1 used snake_case).
const backfill = `
-- Backfill classification for existing V1 requests whose category_hint names a capability or alias.
UPDATE capability_requests SET
  classification_state = 'agent_hint',
  classified_capabilities_json = (
    SELECT json_group_array(DISTINCT slug) FROM (
      SELECT c.slug AS slug FROM capabilities c WHERE c.slug = replace(lower(trim(capability_requests.category_hint)), '_', '-')
      UNION
      SELECT a.capability_slug FROM capability_aliases a WHERE a.alias_slug = replace(lower(trim(capability_requests.category_hint)), '_', '-')
    )
  )
  WHERE category_hint IS NOT NULL
    AND (EXISTS (SELECT 1 FROM capabilities c WHERE c.slug = replace(lower(trim(capability_requests.category_hint)), '_', '-'))
      OR EXISTS (SELECT 1 FROM capability_aliases a WHERE a.alias_slug = replace(lower(trim(capability_requests.category_hint)), '_', '-')));
`;

const out = `${schema}\n-- Seed: ${CAPABILITIES.length} canonical capabilities.\n${seed}\n\n-- Seed: aliases (spec 5.1).\n${aliasSeed}\n${backfill}`;
writeFileSync(new URL('../migrations/0004_capability_registry.sql', import.meta.url), out);
console.log(`Wrote migrations/0004_capability_registry.sql (${CAPABILITIES.length} capabilities, ${ALIASES.length} alias families)`);
